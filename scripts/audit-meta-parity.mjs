#!/usr/bin/env node
/**
 * audit-meta-parity.mjs — served-vs-hydrated meta parity tool (PR-222)
 *
 * Compares the <title> / <meta name="description"> in every prerendered
 * dist/**?/index.html (what Google indexes) against what the hydrated React
 * head would apply via generateSEOMetadata() (what users see).
 *
 * Modes:
 *   node scripts/audit-meta-parity.mjs           # report drift (exit 1 if any)
 *   node scripts/audit-meta-parity.mjs --write   # regenerate src/config/seoParityOverrides.ts
 *
 * --write compares against the BASE config (parity overrides stubbed out via
 * esbuild alias) so regeneration never erases itself. The plain audit mode
 * compares against the FULL config (parity active) — that is the real
 * hydrated behavior and should report zero drift on a healthy build.
 *
 * Run `npx vite build && node scripts/prerender-static.mjs` first — this tool
 * reads dist/. Parse method is tag-anchored regex on our own generated HTML
 * (attribute order is fixed by createHTMLTemplate), with entity decoding.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';
import { createRequire } from 'module';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const dist = path.join(root, 'dist');
const WRITE = process.argv.includes('--write');

if (!fs.existsSync(dist)) {
  console.error('dist/ not found — run the build + prerender first.');
  process.exit(2);
}

// ---- bundle the SEO config for Node consumption ----------------------------
const outFile = path.join(root, 'node_modules', '.cache-seo-parity.cjs');
const overridesPath = path.join(root, 'src/config/seoParityOverrides.ts');
const backupPath = overridesPath + '.parity-bak';
// In --write mode, bundle against a stubbed (empty) overrides file so the
// comparison sees the BASE config — otherwise regeneration would erase itself.
const swap = WRITE && fs.existsSync(overridesPath);
if (swap) {
  fs.renameSync(overridesPath, backupPath);
  fs.writeFileSync(
    overridesPath,
    "import type { SEOMetadata } from './seoTitles';\nexport const SEO_PARITY_OVERRIDES: Record<string, SEOMetadata> = {};\n"
  );
}
try {
  execSync(
    `npx esbuild src/config/seoTitles.ts --bundle --format=cjs --outfile=${outFile}`,
    { cwd: root, stdio: 'pipe' }
  );
} finally {
  if (swap) {
    fs.rmSync(overridesPath);
    fs.renameSync(backupPath, overridesPath);
  }
}
const require = createRequire(import.meta.url);
delete require.cache[outFile];
const { generateSEOMetadata } = require(outFile);

// ---- read served meta from dist --------------------------------------------
const decode = (s) =>
  s
    .replace(/&amp;/g, '&')
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .trim();
const grab = (html, re) => {
  const m = html.match(re);
  return m ? decode(m[1]) : '';
};
const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (f === 'index.html') files.push(p);
  }
})(dist);

const drift = [];
const entries = {};
for (const f of files) {
  const rel = path.relative(dist, path.dirname(f)).replace(/\\/g, '/');
  const route = rel === '' ? '/' : '/' + rel;
  const html = fs.readFileSync(f, 'utf8');
  const served = grab(html, /<title>([^<]*)<\/title>/);
  const servedDesc = grab(html, /<meta name="description" content="([^"]*)"/);
  const servedCanon =
    grab(html, /<link rel="canonical" href="([^"]*)"/) ||
    'https://allphaseconstructionfl.com' + (route === '/' ? '/' : route);
  if (!served) continue;
  let g;
  try {
    g = generateSEOMetadata(route);
  } catch {
    continue;
  }
  // Fallback routes are protected at runtime by the __PRERENDERED_TITLE__
  // guard in NuclearMetadata, so they are parity-safe by construction.
  if (g.isFallback) continue;
  const tMis = g.title !== served;
  const dMis = servedDesc && g.description !== servedDesc;
  if (tMis || dMis) {
    drift.push({ route, served, hydrated: g.title, tMis, dMis });
    entries[route] = {
      title: served,
      description: servedDesc || g.description,
      canonical: servedCanon,
    };
  }
}

if (WRITE) {
  const lines = Object.entries(entries).map(
    ([r, v]) =>
      `  ${JSON.stringify(r)}: { title: ${JSON.stringify(
        v.title
      )}, description: ${JSON.stringify(v.description)}, canonical: ${JSON.stringify(
        v.canonical
      )} },`
  );
  const mod = `// AUTO-GENERATED by scripts/audit-meta-parity.mjs --write — do not hand-edit.
// Purpose: the hydrated <title>/<meta description> must match the prerendered
// (served) HTML that Google indexes. These entries mirror dist/ output for
// every route where the base SEO config had drifted (PR-222).
// Regenerate after any prerender meta change:
//   npx vite build && node scripts/prerender-static.mjs && node scripts/audit-meta-parity.mjs --write
import type { SEOMetadata } from './seoTitles';

export const SEO_PARITY_OVERRIDES: Record<string, SEOMetadata> = {
${lines.join('\n')}
};
`;
  fs.writeFileSync(path.join(root, 'src/config/seoParityOverrides.ts'), mod);
  console.log(
    `Wrote ${Object.keys(entries).length} parity entries to src/config/seoParityOverrides.ts`
  );
  process.exit(0);
}

console.log(`Routes checked: ${files.length} | drift: ${drift.length}`);
for (const d of drift.slice(0, 40))
  console.log(
    `  ${d.route}\n    served:   ${d.served}\n    hydrated: ${d.hydrated}`
  );
if (drift.length > 40) console.log(`  …and ${drift.length - 40} more`);
process.exit(drift.length ? 1 : 0);
